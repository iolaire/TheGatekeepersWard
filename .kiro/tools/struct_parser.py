DARWIN_TYPEDEFS_PREAMBLE = "\n".join(_DARWIN_TYPEDEF_LINES)

# Header macros replaced textually before parsing.
MACRO_SUBSTITUTIONS = {
    "MAXPATHLEN": "1024",
    "OCMAXPATHLEN": "1024",
    "MAXCOMLEN": "16",
    "MAXLOGNAME": "33",
    "SPECNAMELEN": "63",
}

BLOCK_COMMENT_RE = re.compile(r"/\*.*?\*/", re.S)
LINE_COMMENT_RE = re.compile(r"//[^\n]*")
PREPROC_LINE_RE = re.compile(r"^[ \t]*#.*$", re.M)


class StructParseError(Exception):
    """Raised when the input is not a valid C struct definition."""

    def __init__(self, reason: str) -> None:
        self.reason = reason
        super().__init__(reason)


@dataclass
class StructField:
    name: str           # dot-notation for nested: "pvi_cdir.vip_path"
    c_type: str         # e.g. "char [1024]" / "struct vmspace *"
    byte_offset: int    # from outermost struct boundary (arm64)
    byte_size: int
    in_union: bool = False


@dataclass
class StructResult:
    found: bool
    definition: str = ""
    fields: list[StructField] = field(default_factory=list)
    source_header: str = ""
    arm64_byte_size: int = 0
    searched_headers: list[str] = field(default_factory=list)
    error: str | None = None


def _align_up(value: int, alignment: int) -> int:
    return (value + alignment - 1) // alignment * alignment


def _clean_c_text(text: str) -> str:
    text = BLOCK_COMMENT_RE.sub(" ", text)
    text = LINE_COMMENT_RE.sub(" ", text)
    text = PREPROC_LINE_RE.sub("", text)
    for macro, value in MACRO_SUBSTITUTIONS.items():
        text = re.sub(rf"\b{macro}\b", value, text)
    return text


def _unwrap(node):
    """Strip outer TypeDecl wrappers from a Decl's type node."""
    while isinstance(node, TypeDecl):
        node = node.type
    return node


def _eval_dim(node) -> int:
    if isinstance(node, Constant):
        return int(node.value, 0)
    if isinstance(node, BinaryOp) and node.op == "+":
        return _eval_dim(node.left) + _eval_dim(node.right)
    if isinstance(node, BinaryOp) and node.op == "-":
        return _eval_dim(node.left) - _eval_dim(node.right)
    raise StructParseError(f"unsupported array dimension expression: {node!r}")


def _common_prefix(paths: list[list[str]]) -> list[str]:
    if not paths:
        return []
    prefix = list(paths[0])
    for path in paths[1:]:
        k = 0
        while k < len(prefix) and k < len(path) and prefix[k] == path[k]:
            k += 1
        prefix = prefix[:k]
    return prefix


def _render_leaf_decl(c_type: str, name: str) -> str:
    """Render ``c_type name`` as valid C, moving array brackets after the name."""
    m = re.match(r"^(.*?)\[\s*(\d+)\s*\]$", c_type)
    if m:
        return f"{m.group(1).strip()} {name}[{m.group(2)}]"
    return f"{c_type} {name}"


class StructParser:
    """Extracts field layouts from C struct definitions."""

    # Pre-computed registries for the five required structs (hot path).
    KNOWN_STRUCTS: dict[str, list[StructField]] = {
        name: [
            StructField(
                name=f["name"],
                c_type=f["c_type"],
                byte_offset=f["byte_offset"],
                byte_size=f["byte_size"],
                in_union=f["in_union"],
            )
            for f in data["fields"]
        ]
        for name, data in KNOWN_STRUCT_DATA.items()
    }
    KNOWN_DEFINITIONS: dict[str, str] = {
        name: data["definition"] for name, data in KNOWN_STRUCT_DATA.items()
    }
    KNOWN_HEADERS: dict[str, str] = {
        name: data["header"] for name, data in KNOWN_STRUCT_DATA.items()
    }
    KNOWN_SIZES: dict[str, int] = {
        name: data["arm64_byte_size"] for name, data in KNOWN_STRUCT_DATA.items()
    }

    def __init__(self, header_reader, search_budget_s: float = 8.0):
        self._reader = header_reader
        self._search_budget_s = search_budget_s
        self._parser = c_parser.CParser()

    # ------------------------------------------------------------------
    # Public API

    def get_struct(self, struct_name: str) -> StructResult:
        """Return layout for a struct: known table first, then header search."""
        if not isinstance(struct_name, str) or not struct_name.strip():
            return StructResult(found=False, error="struct_name must be a non-empty string")
        name = struct_name.strip()
        if name in self.KNOWN_STRUCTS:
            return StructResult(
                found=True,
                definition=self.KNOWN_DEFINITIONS[name],
                fields=list(self.KNOWN_STRUCTS[name]),
                source_header=str(self._include_root() / self.KNOWN_HEADERS[name]),
                arm64_byte_size=self.KNOWN_SIZES[name],
            )
        return self._search_and_parse(name)

    def parse_struct_text(self, text: str) -> list[StructField]:
        """Parse a raw C struct definition string into flattened fields."""
        fields, _size, _align = self._parse_struct_layout(text)
        return fields

    # ------------------------------------------------------------------
    # Parsing internals

    def _parse_struct_layout(self, text: str) -> tuple[list[StructField], int, int]:
        if not isinstance(text, str) or not text.strip():
            raise StructParseError("empty input: expected a C struct definition")
        cleaned = _clean_c_text(text)
        if "{" not in cleaned or "}" not in cleaned:
            raise StructParseError("input does not look like a C struct definition "
                                   "(missing braces)")
        full_text = DARWIN_TYPEDEFS_PREAMBLE + "\n" + cleaned
        try:
            ast = self._parser.parse(full_text)
        except Exception as exc:  # pycparser.ParseError and lexer errors
            raise StructParseError(f"failed to parse C text: {exc}") from exc
        # Named struct definitions from the whole translation unit, for
        # resolving by-value references.
        structs: dict[str, Struct] = {}
        target = None
        for ext in ast.ext:
            node = ext.type if isinstance(ext, Decl) else None
            if isinstance(node, Struct) and node.decls:
                if node.name:
                    structs[node.name] = node
                target = node
        if target is None:
            raise StructParseError("no struct definition found in input")
        fields, size, align = self._struct_fields(target, "", structs)
        return fields, size, align

    def _struct_fields(self, node: Struct, prefix: str, structs: dict) -> tuple[list[StructField], int, int]:
        """Flatten a struct's members. Offsets are relative to the struct start."""
        fields: list[StructField] = []
        offset = 0
        align = 1
        for decl in node.decls or []:
            tnode = _unwrap(decl.type)
            child_prefix = f"{prefix}.{decl.name}" if prefix and decl.name else (decl.name or prefix)
            if isinstance(tnode, (Struct, Union)):
                m_size, m_align, m_fields = self._member_layout(tnode, child_prefix, structs)
                member_offset = _align_up(offset, m_align)
                for f in m_fields:
                    f.byte_offset += member_offset
                fields.extend(m_fields)
                offset = member_offset + m_size
                align = max(align, m_align)
            else:
                f_size, f_align = self._field_size(tnode)
                offset = _align_up(offset, f_align)
                fields.append(StructField(
                    name=child_prefix,
                    c_type=self.format_type(tnode),
                    byte_offset=offset,
                    byte_size=f_size,
                    in_union=False,
                ))
                offset += f_size
                align = max(align, f_align)
        size = _align_up(offset, align)
        return fields, size, align

    def _union_fields(self, node: Union, prefix: str, structs: dict) -> tuple[list[StructField], int, int]:
        """Flatten a union's members: all share offset 0 and in_union=True.
        Struct/union-typed members are kept whole."""
        fields: list[StructField] = []
        size = 0
        align = 1
        for decl in node.decls or []:
            tnode = _unwrap(decl.type)
            child_prefix = f"{prefix}.{decl.name}" if prefix and decl.name else (decl.name or prefix)
            if isinstance(tnode, (Struct, Union)):
                m_size, m_align = self._node_layout(tnode, structs)
                fields.append(StructField(
                    name=child_prefix,
                    c_type=self.format_type(tnode),
                    byte_offset=0,
                    byte_size=m_size,
                    in_union=True,
                ))
            else:
                f_size, f_align = self._field_size(tnode)
                fields.append(StructField(
                    name=child_prefix,
                    c_type=self.format_type(tnode),
                    byte_offset=0,
                    byte_size=f_size,
                    in_union=True,
                ))
                m_size, m_align = f_size, f_align
            size = max(size, m_size)
            align = max(align, m_align)
        return fields, _align_up(size, align), align

    def _member_layout(self, tnode, child_prefix: str, structs: dict) -> tuple[int, int, list[StructField]]:
        """Layout of a struct/union-typed member; field offsets are relative
        to the member's start."""
        if isinstance(tnode, Union):
            if tnode.decls:
                fields, size, align = self._union_fields(tnode, child_prefix, structs)
                return size, align, fields
            if tnode.name and tnode.name in structs:
                fields, size, align = self._union_fields(structs[tnode.name], child_prefix, structs)
                return size, align, fields
            raise StructParseError(f"cannot resolve size of union '{tnode.name}'")
        # Struct
        if tnode.decls:
            fields, size, align = self._struct_fields(tnode, child_prefix, structs)
            return size, align, fields
        if tnode.name and tnode.name in structs:
            fields, size, align = self._struct_fields(structs[tnode.name], child_prefix, structs)
            return size, align, fields
        raise StructParseError(f"cannot resolve size of struct '{tnode.name}'")

    def _node_layout(self, tnode, structs: dict) -> tuple[int, int]:
        """Size and alignment of a struct/union node without field details."""
        if isinstance(tnode, Union):
            if tnode.decls:
                _fields, size, align = self._union_fields(tnode, "", structs)
                return size, align
            if tnode.name and tnode.name in structs:
                _fields, size, align = self._union_fields(structs[tnode.name], "", structs)
                return size, align
            raise StructParseError(f"cannot resolve size of union '{tnode.name}'")
        if tnode.decls:
            _fields, size, align = self._struct_fields(tnode, "", structs)
            return size, align
        if tnode.name and tnode.name in structs:
            _fields, size, align = self._struct_fields(structs[tnode.name], "", structs)
            return size, align
        raise StructParseError(f"cannot resolve size of struct '{tnode.name}'")

    def _field_size(self, tnode) -> tuple[int, int]:
        """(size, alignment) of a scalar / pointer / array field node."""
        if isinstance(tnode, PtrDecl):
            return 8, 8
        if isinstance(tnode, ArrayDecl):
            elem_size, elem_align = self._field_size(_unwrap(tnode.type))
            return elem_size * _eval_dim(tnode.dim), elem_align
        if isinstance(tnode, TypeDecl):
            return self._named_size(tnode.type)
        return self._named_size(tnode)

    def _named_size(self, inner) -> tuple[int, int]:
        if isinstance(inner, Typedef):
            name = inner.name
        elif isinstance(inner, IdentifierType):
            name = " ".join(inner.names)
        else:
            raise StructParseError(f"unsupported type node: {type(inner).__name__}")
        size = ARM64_PRIMITIVE_SIZES.get(name)
        if size is None:
            raise StructParseError(f"unknown type '{name}' for arm64 layout")
        return size, min(size, 8)

    def format_type(self, tnode) -> str:
        """Render a type node as a c_type string (array dims kept in brackets)."""
        if isinstance(tnode, PtrDecl):
            return self.format_type(_unwrap(tnode.type)) + " *"
        if isinstance(tnode, ArrayDecl):
            return self.format_type(_unwrap(tnode.type)) + f"[{_eval_dim(tnode.dim)}]"
        if isinstance(tnode, TypeDecl):
            inner = tnode.type
        else:
            inner = tnode
        if isinstance(inner, Typedef):
            return inner.name
        if isinstance(inner, Struct):
            if inner.name:
                return f"struct {inner.name}"
            return "struct { " + self._render_inline_members(inner) + "}"
        if isinstance(inner, Union):
            if inner.name:
                return f"union {inner.name}"
            return "union { " + self._render_inline_members(inner) + "}"
        return " ".join(inner.names)

    def _render_inline_members(self, node) -> str:
        parts = []
        for decl in node.decls or []:
            tnode = _unwrap(decl.type)
            if isinstance(tnode, ArrayDecl):
                inner = self.format_type(_unwrap(tnode.type))
                parts.append(f"{inner} {decl.name}[{_eval_dim(tnode.dim)}];")
            else:
                parts.append(f"{self.format_type(tnode)} {decl.name};")
        return " ".join(parts)

    # ------------------------------------------------------------------
    # Header search path

    def _include_root(self) -> Path:
        return self._reader.sdk.root / "usr" / "include"

    def _search_and_parse(self, name: str) -> StructResult:
        include_root = self._include_root()
        if not include_root.is_dir():
            return StructResult(found=False, error=f"SDK include root not found: {include_root}")
        pattern = re.compile(rf"\bstruct\s+{re.escape(name)}\s*\{{")
        searched: list[str] = []
        deadline = time.monotonic() + self._search_budget_s
        last_error: str | None = None
        try:
            candidates = sorted(include_root.rglob("*.h"))
        except OSError as exc:
            return StructResult(found=False, error=f"cannot enumerate headers: {exc}")
        for path in candidates:
            if time.monotonic() > deadline:
                break
            searched.append(str(path))
            try:
                text = self._reader.read_absolute(path).text
            except Exception:
                continue
            match = pattern.search(text)
            if not match:
                continue
            definition = _extract_braced(text, match.start())
            if definition is None:
                continue
            try:
                fields, size, _align = self._parse_struct_layout(definition)
            except StructParseError as exc:
                last_error = str(exc)
                continue
            return StructResult(
                found=True,
                definition=definition,
                fields=fields,
                source_header=str(path),
                arm64_byte_size=size,
            )
        return StructResult(
            found=False,
            searched_headers=searched[:200],
            error=last_error or f"struct '{name}' not found in SDK headers",
        )


def _extract_braced(text: str, start: int) -> str | None:
    """Extract ``struct X { ... };`` starting at ``start`` (comment-aware)."""
    i = text.index("{", start)
    depth = 0
    n = len(text)
    while i < n:
        c = text[i]
        if c == "/" and text[i + 1: i + 2] == "*":
            end = text.find("*/", i)
            i = end + 2 if end != -1 else n
            continue
        if c == "/" and text[i + 1: i + 2] == "/":
            end = text.find("\n", i)
            i = end + 1 if end != -1 else n
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                semi = text.find(";", i)
                if semi == -1:
                    return None
                return " ".join(text[start: semi + 1].split())
        i += 1
    return None


def format_fields_to_struct(fields: list[StructField], struct_name: str = "parsed_struct") -> str:
    """Render a flattened field list back into a canonical C struct definition.

    Rebuilding nests dot-notation paths as anonymous structs and groups
    same-offset ``in_union`` runs back into unions, so that re-parsing the
    output reproduces the identical field list (Property 1 round-trip).
    """
    root: dict = {"kind": "struct", "name": struct_name, "members": []}

    def ensure_path(node: dict, parts: list[str]) -> dict:
        for part in parts:
            child = next((m for m in node["members"]
                          if "leaf" not in m and m.get("name") == part), None)
            if child is None:
                child = {"kind": "struct", "name": part, "members": []}
                node["members"].append(child)
            node = child
        return node

    i = 0
    n = len(fields)
    while i < n:
        f = fields[i]
        if f.in_union:
            run: list[StructField] = []
            j = i
            while j < n and fields[j].in_union and fields[j].byte_offset == f.byte_offset:
                run.append(fields[j])
                j += 1
            paths = [m.name.split(".") for m in run]
            cp = paths[0][:-1] if len(run) == 1 else _common_prefix(paths)
            union_name = cp[-1] if cp else None
            parent = ensure_path(root, cp[:-1])
            union_node: dict = {"kind": "union", "name": union_name, "members": []}
            parent["members"].append(union_node)
            for m in run:
                leaf_name = m.name.split(".")[-1]
                union_node["members"].append({"leaf": m, "name": leaf_name})
            i = j
        else:
            parts = f.name.split(".")
            parent = ensure_path(root, parts[:-1])
            parent["members"].append({"leaf": f, "name": parts[-1]})
            i += 1

    def render(node: dict) -> str:
        if "leaf" in node:
            return _render_leaf_decl(node["leaf"].c_type, node["name"]) + ";"
        inner = " ".join(render(m) for m in node["members"])
        name = f" {node['name']}" if node.get("name") else ""
        return f"{node['kind']} {{ {inner} }}{name};"

    # The outermost struct uses tag form: `struct NAME { ... };`
    inner = " ".join(render(m) for m in root["members"])
    return f"struct {struct_name} {{ {inner} }};"
