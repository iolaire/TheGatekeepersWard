"""C struct offset extraction from Darwin header text (pycparser-based).

Known structs are served from pre-computed arm64 field tables
(`known_structs_data.py`, generated by scripts/gen_known_structs.py from
`clang -Xclang -fdump-record-layouts` output). Unknown structs are located in
SDK headers and parsed live with pycparser.

Flattening conventions (shared with the generator):
- Nested structs in a non-union context are flattened with dot-notation names;
  offsets are absolute from the outermost struct boundary.
- Direct members of a union share the union's base offset and carry
  ``in_union=True``. Struct/union-typed union members are kept WHOLE (not
  flattened) so that all ``in_union`` fields of one union share one offset.
"""
from __future__ import annotations

import re
import time
from dataclasses import dataclass, field
from pathlib import Path

from pycparser import c_parser
from pycparser.c_ast import (
    ArrayDecl,
    BinaryOp,
    Constant,
    Decl,
    IdentifierType,
    PtrDecl,
    Struct,
    TypeDecl,
    Typedef,
    Union,
)

from known_structs_data import KNOWN_STRUCT_DATA

