// Generates VOICEOVER.md from src/narration.json (the single source of truth)
// and the measured scratch durations. Usage:
//   node scripts/sync-voiceover.mjs          write VOICEOVER.md
//   node scripts/sync-voiceover.mjs --check  exit 1 if VOICEOVER.md is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const FPS = 30, SPLASH = 105, LEAD = 0.4, TAIL = 0.8;
const narration = JSON.parse(readFileSync("src/narration.json", "utf8"));
const durations = JSON.parse(readFileSync("src/generated/durations.scratch.json", "utf8"));
const voice = (process.env.VO_VOICE ?? "Samantha");
const rate = process.env.VO_RATE ?? (readFileSync("scripts/generate-scratch-vo.sh", "utf8").match(/VO_RATE:-(\d+)/)?.[1] ?? "?");

const tc = (sec) => `${Math.floor(sec / 60)}:${String(Math.floor(sec % 60)).padStart(2, "0")}`;
let frame = SPLASH;
const rows = narration.map((s) => {
  const v = durations[s.id];
  if (v === undefined) throw new Error(`No measured duration for ${s.id}. Run npm run audio:scratch.`);
  const frames = Math.ceil((LEAD + v + TAIL) * FPS);
  const row = { s, v, start: frame / FPS, end: (frame + frames) / FPS };
  frame += frames;
  return row;
});
const total = frame / FPS;

const out = [
  "# Voiceover Script: Gatekeeper's Ward Demo",
  "",
  "<!-- GENERATED by scripts/sync-voiceover.mjs from src/narration.json. Edit the JSON, then run `npm run voiceover:sync`. -->",
  "",
  "Scene IDs match `src/narration.json` and the files in `public/audio/scratch/<scene-id>.wav`. The spoken copy below is generated from that JSON, so the two stay in sync. To change the words, edit `src/narration.json`, then run `npm run audio:scratch` (it re-syncs this file).",
  "",
  `Scratch cut: **${tc(total)}** (${total.toFixed(1)} s, limit 3:00). Timecodes are cumulative, start after a 3.5 s silent splash card, and include ${LEAD} s lead-in and ${TAIL} s tail per scene. Voice: macOS \`say\`, ${voice}, ${rate} wpm.`,
  "",
  "Everyday language first: the narration explains the idea in everyday terms (pop-up, command, who started it). Technical names (`com.apple.TCC`, `sysctl KERN_PROCARGS2`, Fortress HUD) appear only as small on-screen labels. The spoken copy spells out acronyms (\"A I\") so the scratch voice reads them correctly. When you record yourself, say them naturally.",
  "",
  "## Splash card (silent)",
  "- **ID:** none (fixed-length title card, no narration)",
  `- **Timecode:** 0:00-${tc(SPLASH / FPS)}`,
  "- **Visual cues:** Gate-and-spirits mascot rises, the wordmark lights up, tagline fades in, then the card fades to Scene 1.",
  "",
];
rows.forEach(({ s, v, start, end }, i) => {
  out.push(
    `## Scene ${i + 1}: ${s.title}`,
    `- **ID:** \`${s.id}\``,
    `- **Timecode:** ${tc(start)}-${tc(end)} (voice ${v.toFixed(1)} s)`,
    `- **Impact point:** ${s.impact ?? ""}`,
    `- **Visual cues:** ${s.visual ?? ""}`,
    "",
    `> ${s.text}`,
    ""
  );
});
const text = out.join("\n");

if (process.argv.includes("--check")) {
  const cur = existsSync("VOICEOVER.md") ? readFileSync("VOICEOVER.md", "utf8") : "";
  if (cur !== text) {
    console.error("VOICEOVER.md is out of sync with src/narration.json. Run: npm run voiceover:sync");
    process.exit(1);
  }
  console.log("VOICEOVER.md is in sync.");
} else {
  writeFileSync("VOICEOVER.md", text);
  console.log(`VOICEOVER.md written (${rows.length} scenes, ${tc(total)}).`);
}
